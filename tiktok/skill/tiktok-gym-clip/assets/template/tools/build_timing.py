#!/usr/bin/env python3
"""Turn the aligner's syllables.json into src/timing.js (word beats + caption cards).

usage: build_timing.py <work/syllables.json> <captions.txt> <src/timing.js> [--json timing/timing.json]

captions.txt = what is SHOWN, one line per spoken sentence, same number of words as spoken.txt:
    words separated by spaces      /  = new line        |  = new caption card
    word prefix:  # yellow (numbers, key facts)   ! red (bad, expensive, warning)   + green (good, cheap)
If captions.txt does not exist a draft is written there first (upper-case words, a new card at every pause);
edit it and run again.
"""
import json
import os
import re
import sys

TONE = {"#": "y", "!": "r", "+": "g"}
MAXC, MAXW = 15, 4


def disp(text):
    t = re.sub(r"\{\d+\}", "", text).strip(".,!:;…\"'“”‘’()[]–—-")
    return t.upper()


def draft(tokens, path):
    lines, by = [], {}
    for t in tokens:
        by.setdefault(t["s"], []).append(t)
    for s in sorted(by):
        out, line_chars, line_words, card_lines, prev = [], 0, 0, 1, None
        for t in by[s]:
            w = disp(t["text"])
            mark = "#" if re.match(r"^\d", w) else ""
            if prev is not None:
                pause = t["unit"] != prev["unit"]
                strong = prev["text"].rstrip()[-1:] in ".?!:" and line_words >= 2
                if pause or strong:
                    out.append("|"); line_chars = line_words = 0; card_lines = 1
                elif line_chars + 1 + len(w) > MAXC or line_words >= MAXW:
                    if card_lines >= 2:
                        out.append("|"); card_lines = 1
                    else:
                        out.append("/"); card_lines += 1
                    line_chars = line_words = 0
            out.append(mark + w)
            line_chars += len(w) + (1 if line_words else 0)
            line_words += 1
            prev = t
        lines.append(" ".join(out))
    open(path, "w", encoding="utf-8").write("\n".join(lines) + "\n")


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    syl_path, cap_path, js_path = args[:3]
    json_path = sys.argv[sys.argv.index("--json") + 1] if "--json" in sys.argv else None
    raw = json.load(open(syl_path, encoding="utf-8"))
    tokens = raw["tokens"]
    if not os.path.exists(cap_path):
        draft(tokens, cap_path)
        print(f"wrote a caption draft to {cap_path} - edit line breaks / colours, then run again if you change it")
    specs = [ln.strip() for ln in open(cap_path, encoding="utf-8") if ln.strip() and not ln.lstrip().startswith("//")]
    by = {}
    for t in tokens:
        by.setdefault(t["s"], []).append(t)
    if len(specs) != len(by):
        sys.exit(f"captions.txt has {len(specs)} lines but the recording has {len(by)} sentences")
    words, cards = [], []
    for s, spec in enumerate(specs):
        ws, k = by[s], 0
        for card in spec.split("|"):
            lines = []
            for line in card.split("/"):
                idx = []
                for tok in line.split():
                    if k >= len(ws):
                        sys.exit(f"sentence {s}: captions.txt has more words than spoken.txt ({[w['text'] for w in ws]})")
                    tone = TONE.get(tok[0], "") if len(tok) > 1 else ""
                    w = ws[k]
                    words.append(dict(i=len(words), s=s, k=k, w=tok[1:] if tone else tok, src=w["text"], tone=tone,
                                      a=w["t"], b=w["end"], sub=w["sub"], ipu=w["unit"]))
                    idx.append(len(words) - 1)
                    k += 1
                if idx:
                    lines.append(idx)
            if lines:
                cards.append(dict(s=s, lines=lines))
        if k != len(ws):
            sys.exit(f"sentence {s}: captions.txt has {k} words, spoken.txt has {len(ws)}: {[w['text'] for w in ws]}")
    for c in cards:
        flat = [i for ln in c["lines"] for i in ln]
        c["a"], c["b"] = words[flat[0]]["a"], words[flat[-1]]["b"]
    for i, c in enumerate(cards):
        nxt = cards[i + 1]["a"] if i + 1 < len(cards) else 1e9
        c["hide"] = round(min(nxt, c["b"] + 0.45), 3)
    data = dict(words=words, cards=cards, ipus=raw["units"], duration=raw["duration"])
    open(js_path, "w", encoding="utf-8").write("/* generated by tools/build_timing.py - do not edit */\nwindow.TIMING = " + json.dumps(data, ensure_ascii=False) + ";\n")
    if json_path:
        os.makedirs(os.path.dirname(json_path) or ".", exist_ok=True)
        json.dump(data, open(json_path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"words={len(words)} cards={len(cards)} duration={raw['duration']}s -> {js_path}")


if __name__ == "__main__":
    main()
