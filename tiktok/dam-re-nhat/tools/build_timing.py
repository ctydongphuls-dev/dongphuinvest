#!/usr/bin/env python3
"""Build src/timing.js (word-level timing + caption layout) from the forced-alignment result.

usage: build_timing.py <timing_raw.json> <out timing.js> <out timing.json>

Caption spec per spoken sentence:  words separated by spaces, '/' = new line, '|' = new caption card.
Prefix on a word:  # yellow (numbers / key facts)   ! red (expensive / warning)   + green (cheap / good)
The number of words must match the aligned transcript 1:1.
"""
import json
import sys

CAPS = [
    "TRỨNG !KHÔNG !PHẢI / NGUỒN ĐẠM RẺ NHẤT",
    "WHEY !CÀNG !KHÔNG",
    "MÓN ĐỨNG #TOP #1 | GIÁ CHƯA TỚI / #150 #ĐỒNG | MỘT GRAM ĐẠM",
    "VÀ HẦU HẾT #DÂN #GYM | !KHÔNG !BAO !GIỜ / ĂN NÓ",
    "TAO ĐÃ TÍNH GIÁ / TỪNG GRAM ĐẠM | CỦA #6 #MÓN",
    "XEM TỚI CUỐI | #TOP #1 SẼ LÀM / MÀY !TỨC",
    "HẠNG #6 WHEY",
    "MỘT HŨ / GẦN #2 #TRIỆU | MỖI GRAM ĐẠM / HƠN !1.000 !ĐỒNG",
    "TIỆN THẬT | NHƯNG !ĐẮT / !NHẤT !BẢNG",
    "HẠNG #5 | VÀ ĐÂY LÀ / !CÚ !SỐC | TRỨNG",
    "#3.000 #ĐỒNG / MỘT QUẢ | ĐƯỢC #6 #GRAM / #RƯỠI ĐẠM",
    "TÍNH RA / !460 !ĐỒNG MỘT GRAM | !ÁP !CHÓT",
    "HẠNG #4 / ĐẬU PHỤ | KHOẢNG / #370 #ĐỒNG",
    "HẠNG #3 / ỨC GÀ | #75.000 #ĐỒNG / MỘT CÂN | #330 #ĐỒNG / MỘT GRAM",
    "ĐÚNG ỨC GÀ / +RẺ +HƠN TRỨNG",
    "HẠNG #2 LẠC",
    "CHỈ KHOẢNG / +240 +ĐỒNG | MỘT GRAM",
    "NHƯNG !CẨN !THẬN | 100 GRAM LẠC / GẦN !570 !CALO | ĂN NHIỀU / LÀ !BÉO | CHỨ KHÔNG / PHẢI TO",
    "CÒN #TOP #1 | +ĐẬU +NÀNH +KHÔ",
    "#35K MỘT CÂN | 100 GRAM / CÓ +36 +GRAM +ĐẠM",
    "MỖI GRAM CHỈ / KHOẢNG +100 +ĐỒNG | +RẺ +HƠN TRỨNG / +4 +LẦN | +RẺ +HƠN WHEY / +10 +LẦN",
    "NHỚ #NẤU #CHÍN | LUỘC HẦM RANG / HOẶC XAY SỮA | !ĐỪNG !ĂN !SỐNG",
    "VÀ ĐỪNG BỎ / TRỨNG VỚI ỨC GÀ | CỨ TRỘN THÊM / +ĐẬU +NÀNH VÀO | LÀ TIỀN ĐẠM / CỦA MÀY | +GIẢM +MỘT +NỬA",
    "#LƯU VIDEO / NÀY LẠI | MAI ĐI CHỢ / KHỎI BỊ HỚ",
    "MÀY ĐANG ĂN / MÓN HẠNG MẤY? | #COMMENT / TAO XEM",
]
TONE = {"#": "y", "!": "r", "+": "g"}


def main():
    raw = json.load(open(sys.argv[1], encoding="utf-8"))
    words = raw["words"]
    by_sent = {}
    for w in words:
        by_sent.setdefault(w["sent"], []).append(w)
    out_words, cards = [], []
    for s, spec in enumerate(CAPS):
        ws = by_sent[s]
        k = 0
        for card in spec.split("|"):
            lines = []
            for line in card.split("/"):
                idx = []
                for tok in line.split():
                    tone = TONE.get(tok[0], "")
                    disp = tok[1:] if tone else tok
                    w = ws[k]
                    out_words.append(dict(i=len(out_words), s=s, k=k, w=disp, src=w["word"], tone=tone,
                                          a=w["start"], b=w["end"], ipu=w["ipu"]))
                    idx.append(len(out_words) - 1)
                    k += 1
                lines.append(idx)
            cards.append(dict(s=s, lines=lines))
        assert k == len(ws), f"sentence {s}: caption has {k} words, transcript has {len(ws)}: {[w['word'] for w in ws]}"
    # card show/hide times: appear slightly before the first word, stay until the next card (or a short hold)
    for c in cards:
        flat = [i for ln in c["lines"] for i in ln]
        c["a"] = out_words[flat[0]]["a"]
        c["b"] = out_words[flat[-1]]["b"]
    for i, c in enumerate(cards):
        nxt = cards[i + 1]["a"] if i + 1 < len(cards) else 1e9
        c["hide"] = round(min(nxt, c["b"] + 0.45), 3)
    data = dict(words=out_words, cards=cards, ipus=raw["ipus"], duration=raw.get("duration", 73.287))
    js = "/* generated by tools/build_timing.py - do not edit */\nwindow.TIMING = " + json.dumps(data, ensure_ascii=False) + ";\n"
    open(sys.argv[2], "w", encoding="utf-8").write(js)
    json.dump(data, open(sys.argv[3], "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"words={len(out_words)} cards={len(cards)}")


if __name__ == "__main__":
    main()
